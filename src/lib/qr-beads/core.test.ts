import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import jsQR from 'jsqr';
import { describe, expect, it } from 'vitest';
import { buildQrPattern, QR_MAX_BEADS, QR_MAX_UTF8_BYTES, QrPatternError } from './core';
import type { QrEcc, QrPattern, QrState } from './types';

const input = (patch: Partial<QrState> = {}) => ({ text: 'HELLO', errorCorrection: 'M' as QrEcc, beadsPerModule: 1 as const, ...patch });

// A separate decoder receives rendered RGBA, not any encoder object or its text.
function decode(pattern: QrPattern) {
    const scale = 4, width = pattern.width * scale;
    const pixels = new Uint8ClampedArray(width * width * 4);
    for (let y = 0; y < width; y++) for (let x = 0; x < width; x++) {
        const value = pattern.mask[Math.floor(y / scale) * pattern.width + Math.floor(x / scale)] ? 0 : 255;
        pixels.set([value, value, value, 255], (y * width + x) * 4);
    }
    return jsQR(pixels, width, width, { inversionAttempts: 'dontInvert' });
}

function expectCode(action: () => unknown, code: string) {
    try { action(); throw new Error('Expected a QR validation error'); }
    catch (error) { expect(error).toBeInstanceOf(QrPatternError); expect(error).toHaveProperty('code', code); }
}

// ISO format words for mask patterns 0–7, independently listed rather than
// generated by the vendored encoder's BCH implementation.
const formatWords: Record<QrEcc, number[]> = {
    L: [0x77c4, 0x72f3, 0x7daa, 0x789d, 0x662f, 0x6318, 0x6c41, 0x6976],
    M: [0x5412, 0x5125, 0x5e7c, 0x5b4b, 0x45f9, 0x40ce, 0x4f97, 0x4aa0],
    Q: [0x355f, 0x3068, 0x3f31, 0x3a06, 0x24b4, 0x2183, 0x2eda, 0x2bed],
    H: [0x1689, 0x13be, 0x1ce7, 0x19d0, 0x0762, 0x0255, 0x0d0c, 0x083b],
};

describe('QR symbol encoding and independent reading', () => {
    for (const errorCorrection of ['L', 'M', 'Q', 'H'] as const) {
        for (const beadsPerModule of [1, 2, 3] as const) {
            for (const text of [' https://example.org/a?x=1&y=2\n', 'こんにちは 拼豆 🧵 café']) {
                it(`independently decodes exact UTF-8 text with ${errorCorrection}, ${beadsPerModule} beads/module: ${text}`, () => {
                    const pattern = buildQrPattern({ text, errorCorrection, beadsPerModule });
                    const decoded = decode(pattern);
                    expect(decoded?.data).toBe(text);
                    expect(decoded?.binaryData).toEqual(Array.from(new TextEncoder().encode(text)));
                    expect(decoded?.chunks).toContainEqual({ type: 'eci', assignmentNumber: 26 });
                    expect(decoded?.version).toBe(pattern.version);
                });
            }
        }
        it(`encodes exactly ${errorCorrection}, without upgrading a short input's correction level`, () => {
            const pattern = buildQrPattern(input({ text: 'A', errorCorrection }));
            const points = [...Array.from({ length: 6 }, (_, y) => [8, y]), [8, 7], [8, 8], [7, 8],
                ...Array.from({ length: 6 }, (_, index) => [5 - index, 8])];
            let word = 0;
            points.forEach(([x, y], bit) => { word |= pattern.mask[(y + 4) * pattern.width + x + 4] << bit; });
            expect(formatWords[errorCorrection]).toContain(word);
            for (const other of ['L', 'M', 'Q', 'H'] as const) if (other !== errorCorrection) expect(formatWords[other]).not.toContain(word);
        });
    }

    it('keeps CRLF, spaces and composed/decomposed Unicode unchanged', () => {
        for (const text of [' ', '\r\n', ' \tvalue \r\n', 'é', 'e\u0301', '\u0000A']) {
            expect(decode(buildQrPattern(input({ text })))?.data).toBe(text);
        }
    });

    it('protects complete finder squares and four modules of quiet space, including 2×/3× expansion', () => {
        const finder = ['1111111', '1000001', '1011101', '1011101', '1011101', '1000001', '1111111'];
        const single = buildQrPattern(input());
        expect([single.version, single.modules, single.width, single.height, single.quietModules]).toEqual([1, 21, 29, 29, 4]);
        for (const size of [1, 2, 3] as const) {
            const pattern = buildQrPattern(input({ beadsPerModule: size }));
            expect(pattern.width).toBe(29 * size);
            expect(pattern.darkBeads).toBe(single.darkBeads * size * size);
            let total = 0;
            for (let y = 0; y < pattern.height; y++) for (let x = 0; x < pattern.width; x++) {
                const value = pattern.mask[y * pattern.width + x]; total += value;
                expect(value).toBe(single.mask[Math.floor(y / size) * single.width + Math.floor(x / size)]);
                if (x < 4 * size || y < 4 * size || x >= pattern.width - 4 * size || y >= pattern.height - 4 * size) expect(value).toBe(0);
            }
            expect(total).toBe(pattern.darkBeads);
            for (const [left, top] of [[4, 4], [18, 4], [4, 18]]) {
                for (let y = 0; y < 7; y++) for (let x = 0; x < 7; x++) {
                    expect(pattern.mask[((top + y) * size) * pattern.width + (left + x) * size]).toBe(Number(finder[y][x]));
                }
            }
        }
    });

    it('bounds UTF-8 bytes rather than JavaScript character count and permits large QR versions at scale 1', () => {
        expect(QR_MAX_UTF8_BYTES).toBe(1024);
        for (const text of ['a'.repeat(1024), 'é'.repeat(512), '🧵'.repeat(256)]) {
            const pattern = buildQrPattern(input({ text, errorCorrection: 'H' }));
            expect(pattern.version).toBeGreaterThan(20);
            expect(pattern.width).toBeLessThanOrEqual(QR_MAX_BEADS);
        }
        for (const text of ['a'.repeat(1025), 'é'.repeat(513), '🧵'.repeat(257)]) {
            expectCode(() => buildQrPattern(input({ text })), 'TOO_LONG');
        }
    });

    it('allows a 231-bead result but rejects the next oversized QR geometry without clipping', () => {
        expect(QR_MAX_BEADS).toBe(232);
        expect(buildQrPattern(input({ text: 'a'.repeat(300), beadsPerModule: 3 })).width).toBe(231);
        expectCode(() => buildQrPattern(input({ text: 'a'.repeat(332), beadsPerModule: 3 })), 'TOO_LARGE');
        expectCode(() => buildQrPattern(input({ text: 'a'.repeat(1024), beadsPerModule: 2 })), 'TOO_LARGE');
    });

    it.each(['\ud800', '\udfff', 'a\ud800z', '\ud800\ud800', '\udc00\ud800'])('rejects invalid Unicode %j without substitution', text => {
        expectCode(() => buildQrPattern(input({ text })), 'INVALID_TEXT');
    });
    it('rejects missing data, invalid controls and property getters before encoding', () => {
        expectCode(() => buildQrPattern(input({ text: '' })), 'EMPTY');
        const invalid: unknown[] = [null, [], {}, input({ errorCorrection: 'X' as QrEcc }), input({ beadsPerModule: 0 as 1 }),
            input({ beadsPerModule: 4 as 1 }), input({ beadsPerModule: 1.5 as 1 }), input({ text: 12 as unknown as string }),
            Object.create(input())];
        for (const item of invalid) expectCode(() => buildQrPattern(item as Parameters<typeof buildQrPattern>[0]), 'INVALID_OPTIONS');
        const accessor = { ...input() }; Object.defineProperty(accessor, 'text', { get() { throw new Error('Getter must not run'); }, enumerable: true });
        expectCode(() => buildQrPattern(accessor), 'INVALID_OPTIONS');
    });
    it('allocates independent masks without mutating the input', () => {
        const state = Object.freeze(input()), first = buildQrPattern(state), second = buildQrPattern(state);
        first.mask.fill(0);
        expect(second.darkBeads).toBeGreaterThan(0);
        expect(decode(second)?.data).toBe('HELLO');
    });

    it('retains the exact pinned MIT algorithm apart from the documented module/lint adapters', () => {
        const local = readFileSync('src/lib/qr-beads/vendor/qrcodegen.ts', 'utf8');
        const original = local.replace(/^\/\* eslint-disable[^\n]+\n/, '').replaceAll('export namespace qrcodegen', 'namespace qrcodegen');
        expect(createHash('sha256').update(original).digest('hex')).toBe('1dc03fb5a10e0e2318ea162755bbdb9977ca6ce52cff959e9c9b6deafdccda9c');
        expect(readFileSync('src/lib/qr-beads/vendor/LICENSE', 'utf8')).toBe(original.slice(0, original.indexOf(' */') + 3) + '\n');
    });
});
