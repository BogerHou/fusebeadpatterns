import { build } from 'esbuild';
import { mkdir, readFile, writeFile, copyFile, readdir, rm, cp } from 'node:fs/promises';
import postcss from 'postcss';
import tailwindcss from '@tailwindcss/postcss';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { renderBrandIcon } from './build-brand-icons.mjs';
import { checkExtensionPackage } from './check-extension-package.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const sharedIconSource = path.join(root, 'public/brand/square-bead.svg');
const args = process.argv.slice(2);
const store = args.includes('--store');
if (store) args.splice(args.indexOf('--store'), 1);
const directTransfer = store || args.includes('--enable-editor-transfer');
if (args.includes('--enable-editor-transfer')) args.splice(args.indexOf('--enable-editor-transfer'), 1);
if (args.length && (args.length !== 2 || args[0] !== '--out')) throw new Error('Usage: node scripts/build-extension.mjs [--store] [--enable-editor-transfer] [--out directory]');
const output = path.resolve(root, args[1] || (store ? 'artifacts/bead-capture-store-package' : 'artifacts/bead-capture-extension'));
const marker = '.bead-capture-generated';
if (output === root || output === path.dirname(root)) throw new Error('Choose a dedicated extension output directory.');
await mkdir(output, { recursive: true });
const existing = await readdir(output);
if (existing.length && !existing.includes(marker)) throw new Error('Refusing to replace a nonempty directory not generated by this build.');
const zipPath = `${output}.zip`;
// A failed rebuild must not leave an older ZIP at the expected upload path.
await rm(zipPath, { force: true });
for (const file of existing) await rm(path.join(output, file), { recursive: true, force: true });
await writeFile(path.join(output, marker), 'Generated by scripts/build-extension.mjs\n');
const source = path.join(root, 'extensions/bead-capture');

const platformAdapter = path.join(source, 'src/site-adapter.tsx');
const extensionPlugins = [{
    name: 'packaged-homepage',
    setup(builder) {
        // Only the packaged build substitutes routing/image boundaries. Next
        // continues using its real modules on the production website.
        builder.onResolve({ filter: /^next\/(link|image|navigation)$/ }, ({ path: name }) => ({ path: name, namespace: 'capture-platform' }));
        builder.onLoad({ filter: /.*/, namespace: 'capture-platform' }, ({ path: name }) => ({
            contents: name === 'next/link' ? `export { SiteLink as default } from ${JSON.stringify(platformAdapter)};`
                : name === 'next/image' ? `export { SiteImage as default } from ${JSON.stringify(platformAdapter)};`
                : `export { usePathname, useSearchParams, useRouter } from ${JSON.stringify(platformAdapter)};`,
            resolveDir: root, loader: 'ts',
        }));
        builder.onResolve({ filter: /(?:^|\/)LanguageSwitcher$/ }, () => ({ path: path.join(source, 'src/LanguageSwitcher.tsx') }));
        builder.onLoad({ filter: /\/globals\.css$/ }, async ({ path: file }) => ({
            contents: (await postcss([tailwindcss({ base: root, optimize: true })]).process(await readFile(file, 'utf8'), { from: file })).css,
            loader: 'css', resolveDir: path.dirname(file),
        }));
        builder.onLoad({ filter: /\/pattern-quantization\.ts$/ }, async ({ path: file }) => ({
            contents: (await readFile(file, 'utf8')).replace("new URL('./pattern-quantization.worker.ts', import.meta.url)", "new URL('/quantize-worker.js', import.meta.url)"),
            loader: 'ts', resolveDir: path.dirname(file),
        }));
    },
}];
await build({
    absWorkingDir: root,
    entryPoints: {
        studio: 'extensions/bead-capture/src/studio.tsx',
    },
    outdir: output, bundle: true, splitting: true, format: 'esm', platform: 'browser', target: 'chrome123',
    chunkNames: 'chunks/[name]-[hash]', assetNames: 'assets/[name]-[hash]',
    loader: { '.module.css': 'local-css', '.woff2': 'file' },
    plugins: extensionPlugins,
    minify: true, sourcemap: false, legalComments: 'external', tsconfig: path.join(root, 'tsconfig.json'),
    define: { BEAD_CAPTURE_EDITOR_TRANSFER_ENABLED: JSON.stringify(directTransfer), 'process.env.NODE_ENV': '"production"' },
    metafile: true,
}).then(async (result) => {
    for (const file of Object.keys(result.metafile.outputs)) {
        if (file.endsWith('.js') && (await readFile(path.resolve(root, file), 'utf8')).includes('eval(')) throw new Error('Extension bundle must not use eval.');
    }
    const packages = new Set(Object.keys(result.metafile.inputs).flatMap(file => {
        const match = /(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)/.exec(file);
        return match ? [match[1]] : [];
    }));
    const notices = [];
    for (const name of [...packages].sort()) {
        const directory = path.join(root, 'node_modules', name);
        const files = await readdir(directory);
        const license = files.find(file => /^licen[sc]e(?:\.(?:md|txt))?$/i.test(file));
        if (license) notices.push(`${name}\n${'='.repeat(60)}\n${await readFile(path.join(directory, license), 'utf8')}`);
    }
    await writeFile(path.join(output, 'THIRD-PARTY-NOTICES.txt'), notices.join('\n\n'));
});
// Content scripts are classic scripts, so they must not import split chunks.
await build({
    absWorkingDir: root,
    entryPoints: {
        background: 'extensions/bead-capture/src/background.ts',
        handoff: 'extensions/bead-capture/src/handoff.ts',
        'website-bridge': 'extensions/bead-capture/src/website-bridge.ts',
        'quantize-worker': 'src/lib/editor/pattern-quantization.worker.ts',
    },
    outdir: output, bundle: true, splitting: false, format: 'esm', platform: 'browser', target: 'chrome123',
    minify: true, sourcemap: false, legalComments: 'external', tsconfig: path.join(root, 'tsconfig.json'),
});
for (const file of ['manifest.json', 'studio.html', 'handoff.html', 'loading.css', 'README.md']) await copyFile(path.join(source, file), path.join(output, file));
await cp(path.join(root, 'public/palettes'), path.join(output, 'palettes'), { recursive: true });
await cp(path.join(root, 'public/fonts/fuse-bead-japanese'), path.join(output, 'fonts/fuse-bead-japanese'), { recursive: true });
await mkdir(path.join(output, 'licenses'), { recursive: true });
for (const file of ['Inter-OFL.txt', 'Manrope-OFL.txt']) await copyFile(path.join(source, 'fonts', file), path.join(output, 'licenses', file));
await mkdir(path.join(output, 'icons'));

// Website and extension icons come from one SVG; PNGs are generated locally.
for (const size of [16, 32, 48, 128]) {
    await writeFile(path.join(output, `icons/icon-${size}.png`), await renderBrandIcon(size));
}
await copyFile(sharedIconSource, path.join(output, 'icons/icon.svg'));

const manifest = JSON.parse(await readFile(path.join(output, 'manifest.json'), 'utf8'));
await writeFile(path.join(output, 'build-info.json'), JSON.stringify({
    mode: store ? 'store' : 'development',
    version: manifest.version,
    editorTransfer: directTransfer,
}, null, 2) + '\n');
// Validate the completed directory before it can become an uploadable ZIP.
if (store) await checkExtensionPackage(output);
const packedFiles = (await readdir(output)).filter(file => file !== marker);
const packed = spawnSync('zip', ['-q', '-r', zipPath, ...packedFiles], { cwd: output, encoding: 'utf8' });
if (packed.error || packed.status !== 0) throw new Error('Extension files built, but ZIP packaging needs the zip command. ' + (packed.error?.message || packed.stderr));
console.log(JSON.stringify({ name: manifest.name, version: manifest.version, mode: store ? 'store' : 'development', directory: output, zip: zipPath, directTransfer, remoteCode: false, imageUploads: false }, null, 2));
