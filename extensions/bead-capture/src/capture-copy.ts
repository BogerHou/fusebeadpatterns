const sourceErrorKeys: Record<string, CaptureTextKey> = {
    permission_required: 'permissionRequired',
    permission_denied: 'permissionDenied',
    source_expired: 'sourceExpired',
    unsupported_source: 'unsupportedSource',
    fetch_timeout: 'fetchTimeout',
    fetch_failed: 'fetchFailed',
    unsupported_image: 'unsupportedImage',
    image_too_large: 'imageTooLarge',
    image_dimensions: 'imageDimensions',
};

export function captureSourceErrorKey(error: unknown): CaptureTextKey {
    return error instanceof SourceImportError && Object.hasOwn(sourceErrorKeys, error.code)
        ? sourceErrorKeys[error.code] : 'loadFailed';
}
